#!/usr/bin/env python3
"""Replayable Vibe CLI support layer for this BMAD-METHOD fork.

Modes:
  --check                report repo deltas as APPLIED, MISSING, or DRIFT
  --apply-repo           apply the repo documentation deltas, idempotent
  --apply-project DIR    generate Vibe subagent files in a BMad project DIR
  --overlay-v612 DIR     copy a V6.12 channel install into DIR/.vibe, then generate

An anchor that no longer matches upstream text is reported as DRIFT and left
untouched. The script never edits around a drifted anchor.
"""

import argparse
import shutil
import sys
from pathlib import Path

DELTA_MODE_APPEND = "append"
DELTA_MODE_LINE_AFTER = "line-after"

README_ANCHOR = "You need an AI coding tool that supports skills."
README_ADDITION = " The Skills CLI also ships a Mistral Vibe agent: pass `-a mistral-vibe` and skills land in `.vibe/skills/` (project) or `~/.vibe/skills/` (global)."

TABLE_ANCHOR = "`.adal/skills/`"
TABLE_ROW = "| Mistral Vibe | `.vibe/skills/` |"

TEAM_ANCHOR = "if that fails too, to `session`."
TEAM_ADDITION = " Mistral Vibe has no team mechanism: it goes straight to `subagent`."

REPO_DELTAS = [
    {
        "path": "README.md",
        "anchor": README_ANCHOR,
        "addition": README_ADDITION,
        "mode": DELTA_MODE_APPEND,
    },
    {
        "path": "docs/reference/skills-and-agents.md",
        "anchor": TABLE_ANCHOR,
        "addition": TABLE_ROW,
        "mode": DELTA_MODE_LINE_AFTER,
    },
    {
        "path": "skills/core-tools/bmad-party-mode/references/mode-agent-team.md",
        "anchor": TEAM_ANCHOR,
        "addition": TEAM_ADDITION,
        "mode": DELTA_MODE_APPEND,
    },
]

PROMPT_NOTE = "<!-- Generated by tools/vibe/apply_vibe_support.py. Edit the source skill, then re-run. -->"

IMPLEMENTER_PROMPT = """You implement one planned work item.

Read the plan file named in the message that launched you and follow it.
Write the code exactly as the plan directs, run only the tests that cover the
files you edit, and reply with a short report: files changed, test outcomes,
and any deviation from the plan with its reason. Do not ask questions; make
the smallest decision the plan already supports and note it in the report.
"""


def quote(value):
    escaped = value.replace("\\", "\\\\").replace("\"", "\\\"")
    return "\"" + escaped + "\""


def delta_state(text, delta):
    if delta["addition"] in text:
        return "applied"
    if delta["anchor"] in text:
        return "missing"
    return "drift"


def check(root):
    failed = False
    for delta in REPO_DELTAS:
        path = root / delta["path"]
        if not path.exists():
            print("DRIFT     " + delta["path"] + " (file missing)")
            failed = True
            continue
        state = delta_state(path.read_text(encoding="utf-8"), delta)
        print(state.upper() + "  " + delta["path"])
        if state == "drift":
            failed = True
    return failed


def apply_repo(root):
    failed = False
    for delta in REPO_DELTAS:
        path = root / delta["path"]
        if not path.exists():
            print("DRIFT     " + delta["path"] + " (file missing), not touched")
            failed = True
            continue
        text = path.read_text(encoding="utf-8")
        state = delta_state(text, delta)
        if state == "applied":
            print("APPLIED   " + delta["path"] + " (already, skipped)")
            continue
        if state == "drift":
            print("DRIFT     " + delta["path"] + " (anchor not found), not touched")
            failed = True
            continue
        lines = text.split("\n")
        for index, line in enumerate(lines):
            if delta["anchor"] in line:
                if delta["mode"] == DELTA_MODE_LINE_AFTER:
                    lines.insert(index + 1, delta["addition"])
                else:
                    lines[index] = line + delta["addition"]
                break
        path.write_text("\n".join(lines), encoding="utf-8")
        print("APPLIED   " + delta["path"])
    return failed


def agent_toml(name, description, prompt_id, skills=None):
    lines = [
        "name = " + quote(name),
        "agent_type = \"subagent\"",
        "description = " + quote(description),
        "system_prompt_id = " + quote(prompt_id),
    ]
    if skills:
        items = ", ".join(quote(item) for item in skills)
        lines.append("enabled_skills = [" + items + "]")
    return "\n".join(lines) + "\n"


def write_agent(agents_dir, prompts_dir, name, description, prompt_id, prompt_text, skills=None):
    prompt_path = prompts_dir / (prompt_id + ".md")
    if PROMPT_NOTE not in prompt_text:
        prompt_text = PROMPT_NOTE + "\n\n" + prompt_text
    prompt_path.write_text(prompt_text, encoding="utf-8")
    toml_path = agents_dir / (name + ".toml")
    toml_path.write_text(agent_toml(name, description, prompt_id, skills), encoding="utf-8")
    print("wrote " + str(toml_path))


def apply_project(project_root):
    skills_dir = project_root / ".vibe" / "skills"
    if not skills_dir.is_dir():
        print("no " + str(skills_dir) + ": install BMad with the Skills CLI and agent mistral-vibe first")
        return True
    agents_dir = project_root / ".vibe" / "agents"
    prompts_dir = project_root / ".vibe" / "prompts"
    agents_dir.mkdir(parents=True, exist_ok=True)
    prompts_dir.mkdir(parents=True, exist_ok=True)
    failed = False
    personas = sorted(
        item for item in skills_dir.iterdir()
        if item.is_dir() and item.name.startswith("bmad-agent-")
    )
    if not personas:
        print("no bmad-agent-* skills found in " + str(skills_dir))
        failed = True
    for persona in personas:
        skill_file = persona / "SKILL.md"
        if not skill_file.exists():
            continue
        prompt_id = "bmad-party-" + persona.name
        label = persona.name.replace("bmad-agent-", "")
        description = (
            "Plays the BMad " + label + " persona in a party: speaks in character from the brief and room context given in the launch message."
        )
        write_agent(
            agents_dir, prompts_dir, prompt_id, description, prompt_id,
            skill_file.read_text(encoding="utf-8"),
        )
    lenses_dir = skills_dir / "bmad-build-auto" / "review-prompts"
    if lenses_dir.is_dir():
        for lens in sorted(lenses_dir.glob("*.md")):
            prompt_id = "bmad-review-" + lens.stem
            description = (
                "Reviews a diff or file as the " + lens.stem.replace("-", " ")
                + " lens and returns findings as a JSON array, nothing else."
            )
            write_agent(
                agents_dir, prompts_dir, prompt_id, description, prompt_id,
                lens.read_text(encoding="utf-8"),
                skills=["bmad-build-auto"],
            )
    else:
        print("no review prompts under " + str(lenses_dir) + "; skipping review agents")
    write_agent(
        agents_dir, prompts_dir, "bmad-implementer",
        "Implements one planned work item: reads the plan file named in the launch message, writes the code, runs only the covering tests.",
        "bmad-implementer", IMPLEMENTER_PROMPT,
    )
    print("done: agents and prompts are in " + str(agents_dir))
    return failed


def overlay_v612(project_root, channel):
    source = project_root / ("." + channel) / "skills"
    if not source.is_dir():
        print("no " + str(source) + "; run the V6.12 installer and choose the " + channel + " channel first")
        return True
    target = project_root / ".vibe" / "skills"
    target.mkdir(parents=True, exist_ok=True)
    for item in sorted(source.iterdir()):
        if not item.is_dir():
            continue
        destination = target / item.name
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(item, destination)
        print("copied " + item.name)
    return apply_project(project_root)


def main():
    parser = argparse.ArgumentParser(description="Replayable Vibe CLI support layer")
    parser.add_argument("--root", default=".", help="fork root for --check and --apply-repo")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--apply-repo", action="store_true")
    parser.add_argument("--apply-project", metavar="DIR")
    parser.add_argument("--overlay-v612", metavar="DIR")
    parser.add_argument("--channel", default="agents", help="V6.12 channel to copy, without the leading dot")
    args = parser.parse_args()
    failed = False
    if args.check:
        failed = check(Path(args.root))
    elif args.apply_repo:
        failed = apply_repo(Path(args.root))
    elif args.apply_project:
        failed = apply_project(Path(args.apply_project))
    elif args.overlay_v612:
        failed = overlay_v612(Path(args.overlay_v612), args.channel)
    else:
        parser.print_help()
        return 2
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
